export const LANGUAGES = [
  { id: "th", label: "ไทย" },
  { id: "en", label: "English" },
];

let current = "th";
const listeners = new Set();

/** Resolve the best initial language without touching storage directly. */
export function detectLanguage(navigatorLanguage) {
  const tag = String(navigatorLanguage ?? "").toLowerCase();
  return tag.startsWith("th") ? "th" : tag === "" ? "th" : "en";
}

export function setLanguage(language) {
  const next = language in STRINGS ? language : "th";
  if (next === current) return current;
  current = next;
  for (const listener of listeners) listener(current);
  return current;
}

export function getLanguage() {
  return current;
}

export function onLanguageChange(listener) {
  listeners.add(listener);
  return () => listeners.delete(listener);
}

const interpolate = (template, params) =>
  params === undefined
    ? template
    : template.replace(/\{(\w+)\}/g, (match, key) =>
        key in params ? String(params[key]) : match,
      );

/** Translate `key`; returns the key when neither language defines it. */
export function t(key, params) {
  const table = STRINGS[current] ?? STRINGS.en;
  const value = table[key] ?? STRINGS.en[key] ?? key;
  return interpolate(value, params);
}

/** Localised, human readable error message for a tagged failure. */
export function describeError(error) {
  const code = error?.code ?? "common.error";
  return t(code in STRINGS.en ? code : "common.error");
}
