export function t2(
  lang: Language,
  key: string,
  param?: string | number
): string {
  const raw = EXTRA[lang]?.[key] ?? EXTRA.en[key] ?? key;
  return param !== undefined ? raw.replace("%s", String(param)) : raw;
}

export function languageLabel(lang: Language): string {
  return { th: "ไทย", en: "English", ja: "日本語", ko: "한국어" }[lang];
}
